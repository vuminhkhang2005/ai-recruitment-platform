import React, { useEffect, useRef, useState } from 'react';
import { ChevronDown, Download, FileSpreadsheet, Loader2, Printer } from 'lucide-react';
import { useToast } from '../../context/ToastContext';
import { useLanguage } from '../../i18n/LanguageContext';
import type { ExportLang } from '../../lib/api';

interface ExportMenuProps {
  /** Downloads the CSV in the given language. */
  onExportCsv: (lang: ExportLang) => Promise<void>;
  /** Show the "Print / Save as PDF" item (uses the browser print dialog + print stylesheet). */
  allowPrint?: boolean;
  disabled?: boolean;
  className?: string;
  testId?: string;
}

/**
 * "Export" dropdown used on recruiter and admin pages.
 * - CSV: generated by the backend (UTF-8 BOM, opens correctly in Excel).
 * - PDF: browser print dialog with the print stylesheet in index.css (navigation and buttons are hidden).
 */
export const ExportMenu: React.FC<ExportMenuProps> = ({ onExportCsv, allowPrint = true, disabled, className = '', testId = 'export-menu' }) => {
  const { language } = useLanguage();
  const isVi = language === 'vi';
  const toast = useToast();
  const [open, setOpen] = useState(false);
  const [busy, setBusy] = useState(false);
  const ref = useRef<HTMLDivElement>(null);

  useEffect(() => {
    if (!open) return;
    const onDoc = (e: MouseEvent) => {
      if (ref.current && !ref.current.contains(e.target as Node)) setOpen(false);
    };
    const onKey = (e: KeyboardEvent) => e.key === 'Escape' && setOpen(false);
    document.addEventListener('mousedown', onDoc);
    document.addEventListener('keydown', onKey);
    return () => {
      document.removeEventListener('mousedown', onDoc);
      document.removeEventListener('keydown', onKey);
    };
  }, [open]);

  const runCsv = async () => {
    setOpen(false);
    setBusy(true);
    try {
      await onExportCsv(isVi ? 'vi' : 'en');
      toast(isVi ? 'Đã tải xuống tệp CSV' : 'CSV file downloaded', 'success');
    } catch (e) {
      toast((e as Error).message || (isVi ? 'Xuất CSV thất bại' : 'CSV export failed'), 'error');
    } finally {
      setBusy(false);
    }
  };

  const runPrint = () => {
    setOpen(false);
    // Let the menu close before the print snapshot is taken
    setTimeout(() => window.print(), 50);
  };

  const itemCls =
    'w-full flex items-center gap-2.5 px-3 py-2 text-left text-sm font-semibold text-slate-700 dark:text-slate-200 hover:bg-emerald-50 dark:hover:bg-emerald-950/40 rounded-lg';

  return (
    <div ref={ref} className={`relative no-print ${className}`} data-testid={testId}>
      <button
        type="button"
        disabled={disabled || busy}
        onClick={() => setOpen((o) => !o)}
        aria-haspopup="menu"
        aria-expanded={open}
        className="inline-flex items-center gap-1.5 px-3 py-2 rounded-xl border border-slate-200 dark:border-slate-700 bg-white dark:bg-slate-900 text-sm font-bold text-slate-700 dark:text-slate-200 hover:border-emerald-400 hover:text-emerald-700 dark:hover:text-emerald-300 disabled:opacity-50 transition-colors"
      >
        {busy ? <Loader2 className="w-4 h-4 animate-spin" /> : <Download className="w-4 h-4" />}
        {isVi ? 'Xuất báo cáo' : 'Export'}
        <ChevronDown className="w-3.5 h-3.5" />
      </button>
      {open && (
        <div
          role="menu"
          className="absolute right-0 mt-1.5 w-56 z-40 p-1.5 rounded-xl border border-slate-200 dark:border-slate-700 bg-white dark:bg-slate-900 shadow-lg"
        >
          <button type="button" role="menuitem" className={itemCls} onClick={runCsv} data-testid={`${testId}-csv`}>
            <FileSpreadsheet className="w-4 h-4 text-emerald-600" />
            <span>
              {isVi ? 'Tải CSV (Excel)' : 'Download CSV (Excel)'}
            </span>
          </button>
          {allowPrint && (
            <button type="button" role="menuitem" className={itemCls} onClick={runPrint} data-testid={`${testId}-print`}>
              <Printer className="w-4 h-4 text-sky-600" />
              <span>{isVi ? 'In / Lưu PDF' : 'Print / Save as PDF'}</span>
            </button>
          )}
        </div>
      )}
    </div>
  );
};
